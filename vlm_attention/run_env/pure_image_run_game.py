from fileinput import filename
import time
from datetime import datetime
from absl import app
from absl import flags
import os
import cv2

from vlm_attention.env.env_core import SC2MultimodalEnv
from vlm_attention import ROOT_DIR, CONFIG_FILE_RELATIVE_PATH
from vlm_attention.vlm.gemini_vlm import (
    GeminiVLM,
    AGGRESSIVE_PERSONALITY,
    PASSIVE_PERSONALITY
)


"""
Run the environment with a Gemini VLM making decisions.

Runs the game agent and connects model decisions to in-game actions.

Pipeline:

SC2 Environment
    -> screenshot + unit information
    -> Gemini VLM
    -> constrained command
    -> SC2 action
    -> repeat
"""


FLAGS = flags.FLAGS

flags.DEFINE_string(
    "map",
    "vlm_attention_2vAI",
    "Name of the map to use"
)

flags.DEFINE_string(
    "replay_dir",
    "./replays",
    "Directory to save replays"
)

flags.DEFINE_string(
    "config_path",
    os.path.join(ROOT_DIR, CONFIG_FILE_RELATIVE_PATH),
    "Path to the configuration file"
)

# Gemini player configuration for each map.
# Marine counts in map names do not determine player counts.
MAP_CONFIGS = {
    "vlm_3v3_marines": {
        "gemini_players": 1
    },
    "vlm_attention_2vAI": {
        "gemini_players": 2
    }
}

class PureImageAgent:

    def __init__(self, action_space, map_name):

        self.action_space = action_space
        self.map_name = map_name

        # Determine the number of Gemini-controlled players.
        # Unlisted maps retain the existing single-Gemini behavior.
        map_config = MAP_CONFIGS.get(
            map_name,
            {"gemini_players": 1}
        )

        self.gemini_player_count = map_config["gemini_players"]

        # Keep screenshot saving for the assignment.
        self.screenshot_dir = "./pure_screenshots"
        self.screenshot_count = 0
        self.observation_count = 0

        # Ask the VLM every 10 environment steps.
        self.observation_interval = 10
        self.step_count = 0

        # Player 1: Aggressive Gemini commander
        self.gemini_player_1 = GeminiVLM(
            personality=AGGRESSIVE_PERSONALITY
        )

        # Player 2: Passive Gemini commander
        # Only initialize when the selected map requires two Gemini players.
        self.gemini_player_2 = None

        if self.gemini_player_count >= 2:
            self.gemini_player_2 = GeminiVLM(
                personality=PASSIVE_PERSONALITY
            )

        os.makedirs(self.screenshot_dir, exist_ok=True)

    def get_action(self, observation):

        self.step_count += 1

        # Prepare an empty action for each Gemini player.
        empty_action = {
            "attack": [],
            "move": []
        }

        if self.gemini_player_count == 1:
            observations = [observation]
            gemini_players = [self.gemini_player_1]
        else:
            observations = observation
            gemini_players = [
                self.gemini_player_1,
                self.gemini_player_2
            ]

        # Between VLM decisions, do nothing.
        if self.step_count % self.observation_interval != 0:

            if self.gemini_player_count == 1:
                return empty_action

            return [
                empty_action.copy()
                for _ in gemini_players
            ]

        decisions = []
        actions = []
        screenshot_paths = []

        # Each Gemini player receives its own observation.
        for index, (gemini, player_observation) in enumerate(
            zip(gemini_players, observations)
        ):

            screenshot_path = self.capture_observation(
                player_observation,
                save_screenshot=(index == 0)
            )

            screenshot_paths.append(screenshot_path)

            decision = gemini.decide(
                screenshot_path,
                player_observation["unit_info"]
            )

            decisions.append(decision)

            action = self.command_to_action(
                decision["command"],
                player_observation["unit_info"]
            )

            actions.append(action)

        # Display both observations together.
        self.display_observation(
            observations,
            screenshot_paths
        )

        # Display both decisions together.
        print("\n" + "=" * 60)
        print("VLM DECISIONS")
        print("=" * 60)

        for index, decision in enumerate(decisions):

            personality = (
                "Aggressive"
                if index == 0
                else "Passive"
            )

            print(f"\nPlayer {index + 1} ({personality}):")
            print(f"Command: {decision['command']}")
            print(f"Reason:  {decision['reason']}")

        print("=" * 60)

        # Display the actions generated by each player.
        print("SC2 ACTION")

        for index, action in enumerate(actions):

            print(f"\nPlayer {index + 1}:")
            print(action)

        print("=" * 60)

        # Preserve the original single-player action format.
        if self.gemini_player_count == 1:
            return actions[0]

        # Two-player maps return one action per Gemini player.
        return actions

    def capture_observation(self, observation, save_screenshot=True):

        # Save the screenshot only when requested.
        frame = observation["image"]

        if save_screenshot:

            self.screenshot_count += 1

            filename = os.path.join(
                self.screenshot_dir,
                f"observation_{self.screenshot_count:04d}.png"
            )

            cv2.imwrite(
                filename,
                cv2.cvtColor(frame, cv2.COLOR_RGB2BGR)
            )

            print(f"Screenshot saved: {filename}")

        else:
            filename = os.path.join(
                self.screenshot_dir,
                "temporary_player_2.png"
            )

            cv2.imwrite(
                filename,
                cv2.cvtColor(frame, cv2.COLOR_RGB2BGR)
            )

        # Return the screenshot path so Gemini can use it.
        return filename

    def format_unit_info(self, unit_info):

        friendly_units = []
        enemy_units = []

        for unit in unit_info:

            # In this environment:
            # alliance 1 = friendly
            # alliance 4 = enemy
            alliance = unit["alliance"]

            unit_description = (
                f"{unit['unit_name']} "
                f"(tag={unit['simplified_tag']})\n"
                f"  Health: {unit['health']}/{unit['max_health']}\n"
                f"  Position: {unit['position']}"
            )

            if alliance == 1:
                friendly_units.append(unit_description)

            elif alliance == 4:
                enemy_units.append(unit_description)

        result = "FRIENDLY UNITS:\n"

        if friendly_units:
            result += "\n\n".join(friendly_units)
        else:
            result += "None visible"

        result += "\n\nENEMY UNITS:\n"

        if enemy_units:
            result += "\n\n".join(enemy_units)
        else:
            result += "None visible"

        return result

    def format_unit_list(self, units):

        if not units:
            return "None visible"

        return "\n\n".join(
            f"{unit['unit_name']} "
            f"(tag={unit['simplified_tag']})\n"
            f"  Health: {unit['health']}/{unit['max_health']}\n"
            f"  Position: {unit['position']}"
            for unit in units
        )

    def format_combined_unit_info(self, observations):

        player1_units = [
            unit for unit in observations[0]["unit_info"]
            if unit["alliance"] == 1
        ]

        player2_units = [
            unit for unit in observations[1]["unit_info"]
            if unit["alliance"] == 1
        ]

        # Display the enemy group once, using Player 1's observation.
        enemy_units = [
            unit for unit in observations[0]["unit_info"]
            if unit["alliance"] == 4
        ]

        result = "PLAYER 1 UNITS (Aggressive):\n"
        result += self.format_unit_list(player1_units)

        result += "\n\nPLAYER 2 UNITS (Passive):\n"
        result += self.format_unit_list(player2_units)

        result += "\n\nENEMY UNITS:\n"
        result += self.format_unit_list(enemy_units)

        return result

    def display_observation(self, observations, screenshot_paths):

        self.observation_count += 1

        print("\n" + "=" * 60)
        print(f"OBSERVATION #{self.observation_count}")
        print(f"GAME STEP: {self.step_count}")
        print("=" * 60)

        if self.gemini_player_count == 1:

            print(self.format_unit_info(
                observations[0]["unit_info"]
            ))

        else:

            print(self.format_combined_unit_info(observations))

        print("=" * 60)

        for index, path in enumerate(screenshot_paths):

            if index == 0:
                print(f"Player 1 screenshot saved: {path}")

            else:
                print("Player 2 screenshot used for Gemini (not retained as a numbered screenshot).")

        print("=" * 60)

    def command_to_action(self, command, unit_info):

        """
        Convert the VLM command into the action format
        expected by SC2MultimodalEnv.

        Supported commands:

            ATTACK <enemy>
            MOVE <unit> <x,y>
            RETREAT <unit>
            HOLD
        """

        command = command.strip()

        # ==================================================
        # HOLD
        # ==================================================

        if command.upper() == "HOLD":

            return {
                "attack": [],
                "move": []
            }

        # ==================================================
        # ATTACK <enemy>
        # ==================================================

        if command.upper().startswith("ATTACK "):

            target_name = command[7:].strip()

            friendly_tags = []
            enemy_tag = None

            for unit in unit_info:

                if unit["alliance"] == 1:

                    friendly_tags.append(
                        unit["simplified_tag"]
                    )

                elif unit["alliance"] == 4:

                    if (
                        unit["unit_name"].lower()
                        == target_name.lower()
                    ):
                        enemy_tag = unit["simplified_tag"]

            if enemy_tag is None:

                print(
                    f"WARNING: Could not find enemy "
                    f"'{target_name}'."
                )

                return {
                    "attack": [],
                    "move": []
                }

            # ATTACK <enemy> means all surviving
            # friendly units attack that enemy.
            attacks = [
                (friendly_tag, enemy_tag)
                for friendly_tag in friendly_tags
            ]

            return {
                "attack": attacks,
                "move": []
            }

        # ==================================================
        # RETREAT <unit>
        # ==================================================

        if command.upper().startswith("RETREAT "):

            unit_name = command[8:].strip()

            retreat_unit = None

            for unit in unit_info:

                if (
                    unit["alliance"] == 1
                    and unit["unit_name"].lower()
                    == unit_name.lower()
                ):

                    retreat_unit = unit
                    break

            if retreat_unit is None:

                print(
                    f"WARNING: Could not find friendly "
                    f"unit '{unit_name}'."
                )

                return {
                    "attack": [],
                    "move": []
                }

            # Move away from the nearest visible enemy.
            # Direction encoding:
            # 0 = up
            # 1 = right
            # 2 = down
            # 3 = left

            enemy_units = [
                unit for unit in unit_info
                if unit["alliance"] == 4
            ]

            direction = 3  # Default to left if no enemy is visible.

            if enemy_units:
                ux, uy = retreat_unit["position"]

                nearest_enemy = min(
                    enemy_units,
                    key=lambda enemy: (
                        (ux - enemy["position"][0]) ** 2
                        + (uy - enemy["position"][1]) ** 2
                    )
                )

                ex, ey = nearest_enemy["position"]

                # Move along the axis with the larger separation.
                if abs(ux - ex) >= abs(uy - ey):
                    direction = 1 if ux >= ex else 3
                else:
                    direction = 2 if uy >= ey else 0

            move = [
                (
                    2,
                    retreat_unit["simplified_tag"],
                    [direction, 0]
                )
            ]

            return {
                "attack": [],
                "move": move
            }

        # ==================================================
        # MOVE <unit> <x,y>
        # ==================================================

        if command.upper().startswith("MOVE "):

            move_text = command[5:].strip()

            # Expected format:
            #
            # MOVE <unit> <x,y>
            #
            # Example:
            #
            # MOVE Stalker_1 7,5

            parts = move_text.rsplit(" ", 1)

            if len(parts) != 2:

                print(
                    f"WARNING: Invalid MOVE command: "
                    f"{command}"
                )

                return {
                    "attack": [],
                    "move": []
                }

            unit_name = parts[0].strip()
            location_text = parts[1].strip()

            # Parse x,y.
            try:

                x_str, y_str = location_text.split(",")

                x = int(x_str)
                y = int(y_str)

            except (ValueError, TypeError):

                print(
                    f"WARNING: Invalid MOVE location: "
                    f"{location_text}"
                )

                return {
                    "attack": [],
                    "move": []
                }

            # Grid coordinates must be 1 through 10.
            if not (1 <= x <= 10 and 1 <= y <= 10):

                print(
                    f"WARNING: MOVE location must be "
                    f"between 1 and 10: ({x}, {y})"
                )

                return {
                    "attack": [],
                    "move": []
                }

            # Find the friendly unit.
            unit_tag = None

            for unit in unit_info:

                if (
                    unit["alliance"] == 1
                    and unit["unit_name"].lower()
                    == unit_name.lower()
                ):

                    unit_tag = unit["simplified_tag"]
                    break

            if unit_tag is None:

                print(
                    f"WARNING: Could not find friendly "
                    f"unit '{unit_name}'."
                )

                return {
                    "attack": [],
                    "move": []
                }

            # Environment grid movement format:
            #
            # (move_type, unit_tag, [x, y])
            #
            # move_type = 1 means grid-based movement.

            move = [
                (
                    1,
                    unit_tag,
                    [x, y]
                )
            ]

            return {
                "attack": [],
                "move": move
            }

        # ==================================================
        # UNKNOWN COMMAND
        # ==================================================

        print(
            f"WARNING: Unknown VLM command: {command}"
        )

        return {
            "attack": [],
            "move": []
        }


def run_episode(env, agent, max_steps=100):

    observation = env.reset()

    total_reward = 0
    done = False
    step = 0

    # Give StarCraft II a few seconds to initialize.
    time.sleep(3)

    while not done and step < max_steps:

        action = agent.get_action(observation)

        observation, reward, done, _ = env.step(action)

        total_reward += reward
        step += 1

        print(
            f"Step: {step}, "
            f"Reward: {reward}, "
            f"Total Reward: {total_reward}"
        )

    return total_reward


def main(argv):

    del argv

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    save_dir = os.path.abspath(
        "./pure_screenshots"
    )

    replay_dir = os.path.abspath(
        FLAGS.replay_dir
    )

    env = SC2MultimodalEnv(
        map_name=FLAGS.map,
        save_dir=save_dir,
        replay_dir=replay_dir,
        timestamp=timestamp,
        feature_dims=(256, 256),
        rgb_dims=(1280, 720),
        map_size=(64, 64),
        gemini_player_count=MAP_CONFIGS.get(
            FLAGS.map,
            {"gemini_players": 1}
        )["gemini_players"]
    )

    agent = PureImageAgent(
        env.action_space,
        FLAGS.map
    )

    num_episodes = 1

    try:
        for episode in range(num_episodes):

            print(
                f"\nStarting Episode {episode + 1}"
            )

            total_reward = run_episode(
                env,
                agent
            )

            print(
                f"Episode {episode + 1} finished. "
                f"Total Reward: {total_reward}"
            )
    finally:
        env.close()


if __name__ == "__main__":
    app.run(main)
